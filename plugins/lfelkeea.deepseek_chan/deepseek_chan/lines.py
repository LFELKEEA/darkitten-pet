def pick(kind: str, fallback: tuple[str, ...] = ()) -> str:
    pool = LINES.get(kind) or list(fallback)
    if not pool:
        return ""
    return random.choice(pool)


def greeting_for_hour(hour: int) -> str:
    if 5 <= hour < 11:
        bucket = "morning"
    elif 11 <= hour < 14:
        bucket = "noon"
    elif 14 <= hour < 18:
        bucket = "afternoon"
    elif 18 <= hour < 23:
        bucket = "evening"
    else:
        bucket = "night"
    return random.choice(GREETINGS[bucket])


def reaction_line(text: str) -> str:
    compact = str(text or "").lower()
    if any(word in compact for word in ("喜欢", "可爱", "厉害", "好看", "棒", "谢谢", "爱你")):
        return pick("praise")
    if any(word in compact for word in ("笨", "慢", "没用", "垃圾", "蠢", "错了", "不对")):
        return pick("scold")
    if any(word in compact for word in ("怎么", "为什么", "如何", "?", "？", "报错")):
        return pick("question")
    if any(word in compact for word in ("累", "困", "加班", "不想干")):
        return "累了就先停一下。我在这儿，不会催你。"
    if any(word in compact for word in ("吃", "饿", "饭", "奶茶")):
        return pick("food")
    return ""
